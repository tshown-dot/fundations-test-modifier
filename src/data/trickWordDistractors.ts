// Returns a shuffled 3-option array containing the word + 2 distractors
export function getTrickWordOptions(word: string): string[] {
  const cleanWord = word.trim().replace(/[.,!?;:]/g, '');
  const distractors = TRICK_WORD_DISTRACTORS[cleanWord.toLowerCase()] || [
    cleanWord + 'e',
    cleanWord.slice(0, -1) + 'll',
  ];

  // Deterministic order: Distractor 1, Correct, Distractor 2 (or mixed)
  return [distractors[0], cleanWord, distractors[1]];
}
